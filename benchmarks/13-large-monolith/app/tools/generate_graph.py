#!/usr/bin/env python3
"""Generate the large-monolith component graph as Java source.

The graph has MODULES chains of DEPTH components. Inside a chain each component depends on the
one before it (its primary). From the second module on, each component also depends on the same
row of the previous module (its secondary). Dependencies only point backwards, so the graph is
acyclic. The generated classes are ordinary beans: the application's container instantiates them
by reflection, dependencies first, from their constructor parameters.

Usage: generate_graph.py --out DIR [--modules N] [--depth N]
"""

from __future__ import annotations

import argparse
from pathlib import Path

PACKAGE = "com.palaashatri.bench.b13.app.graph"
DEFAULT_MODULES = 20
DEFAULT_DEPTH = 50
# Must match MonolithServer.INPUT and the arithmetic in Mix.java.
INPUT = 0x5DEECE66D
MASK = (1 << 64) - 1


def rotl(value: int, bits: int) -> int:
    return ((value << bits) | (value >> (64 - bits))) & MASK


def derive(tag: int, first: int, second: int) -> int:
    h = (tag * 0x9E3779B97F4A7C15) & MASK
    h ^= (rotl(first, 21) * 0xC2B2AE3D27D4EB4F) & MASK
    h ^= (rotl(second, 42) * 0x165667B19E3779F9) & MASK
    return h ^ (h >> 29)


def step(value: int, seed: int) -> int:
    x = ((value ^ seed) * 0xFF51AFD7ED558CCD) & MASK
    x ^= x >> 33
    return (x + seed) & MASK


def expected_result(modules: int, depth: int) -> int:
    """Independent model of the wiring and the traversal, returned as a signed 64-bit value."""
    seeds: dict[tuple[int, int], int] = {}
    for module in range(modules):
        for row in range(depth):
            tag = (module + 1) * 1000 + row + 1
            first = seeds[(module, row - 1)] if row > 0 else 0
            second = seeds[(module - 1, row)] if module > 0 else 0
            seeds[(module, row)] = derive(tag, first, second)
    value = INPUT
    for module in range(modules):
        for row in reversed(range(depth)):
            value = step(value, seeds[(module, row)])
    return value - (1 << 64) if value >= 1 << 63 else value


def bean_id(module: int, row: int) -> str:
    return f"m{module:02d}-r{row:02d}"


def class_name(module: int, row: int) -> str:
    return f"Node_m{module:02d}_r{row:02d}"


def node_source(module: int, row: int) -> str:
    tag = (module + 1) * 1000 + row + 1
    dependencies: list[tuple[str, str]] = []
    if row > 0:
        dependencies.append(("primary", bean_id(module, row - 1)))
    if module > 0:
        dependencies.append(("secondary", bean_id(module - 1, row)))

    parameters = ", ".join(f'@Dep("{bean}") Component {role}' for role, bean in dependencies)
    fields = [f"    private final Component {role};" for role, _ in dependencies]
    assignments = [f"        this.{role} = {role};" for role, _ in dependencies]
    present = {role for role, _ in dependencies}
    seed_inputs = [f"{role}.seed()" if role in present else "0L" for role in ("primary", "secondary")]

    if row > 0:
        apply_body = "        return primary.apply(Mix.step(value, seed));"
    else:
        apply_body = "        return Mix.step(value, seed);"

    lines = [
        f"package {PACKAGE};",
        "",
        "import com.palaashatri.bench.b13.app.Bean;",
        "import com.palaashatri.bench.b13.app.Component;",
        "import com.palaashatri.bench.b13.app.Dep;",
        "import com.palaashatri.bench.b13.app.Mix;",
        "",
        f'@Bean("{bean_id(module, row)}")',
        f"public final class {class_name(module, row)} implements Component {{",
        *fields,
        "    private final long seed;",
        "",
        f"    public {class_name(module, row)}({parameters}) {{",
        *assignments,
        f"        this.seed = Mix.derive({tag}L, {seed_inputs[0]}, {seed_inputs[1]});",
        "    }",
        "",
        "    @Override",
        "    public long seed() {",
        "        return seed;",
        "    }",
        "",
        "    @Override",
        "    public long apply(long value) {",
        apply_body,
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def manifest_source(modules: int, depth: int) -> str:
    names = [f'        "{PACKAGE}.{class_name(m, r)}",'
             for m in range(modules) for r in range(depth)]
    lines = [
        f"package {PACKAGE};",
        "",
        "/** Generated by tools/generate_graph.py. Do not edit. */",
        "public final class Manifest {",
        f"    public static final int MODULES = {modules};",
        f"    public static final int DEPTH = {depth};",
        f"    public static final long EXPECTED_RESULT = {expected_result(modules, depth)}L;",
        "    public static final String[] BEAN_CLASSES = {",
        *names,
        "    };",
        "",
        "    private Manifest() { }",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the large-monolith component graph.")
    parser.add_argument("--out", type=Path, required=True, help="source root to write into")
    parser.add_argument("--modules", type=int, default=DEFAULT_MODULES)
    parser.add_argument("--depth", type=int, default=DEFAULT_DEPTH)
    args = parser.parse_args()
    if args.modules < 1 or args.depth < 1:
        parser.error("--modules and --depth must be at least 1")

    package_dir = args.out.joinpath(*PACKAGE.split("."))
    package_dir.mkdir(parents=True, exist_ok=True)
    for stale in package_dir.glob("*.java"):
        stale.unlink()
    for module in range(args.modules):
        for row in range(args.depth):
            (package_dir / f"{class_name(module, row)}.java").write_text(node_source(module, row))
    (package_dir / "Manifest.java").write_text(manifest_source(args.modules, args.depth))
    print(f"generated {args.modules * args.depth} components into {package_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
